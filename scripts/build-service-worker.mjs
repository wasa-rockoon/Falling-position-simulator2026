import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, '..');

function localPageAssets(html) {
    return [...html.matchAll(/<(?:script|link)\b[^>]*(?:src|href)=["']([^"']+)["']/gi)]
        .map((match) => match[1])
        .filter((asset) => !/^(?:https?:|data:|#)/i.test(asset))
        .map((asset) => asset.split(/[?#]/, 1)[0]);
}

async function directoryAssets(relativeDirectory) {
    const absoluteDirectory = path.join(projectRoot, relativeDirectory);
    const entries = await fs.readdir(absoluteDirectory, { withFileTypes: true });
    return entries
        .filter((entry) => entry.isFile())
        .map((entry) => path.posix.join(relativeDirectory.replaceAll('\\', '/'), entry.name));
}

function normalizeAsset(asset) {
    const normalized = asset.replaceAll('\\', '/').replace(/^\.\//, '');
    return normalized === '' ? './' : `./${normalized}`;
}

const html = await fs.readFile(path.join(projectRoot, 'index.html'), 'utf8');
const assets = new Set([
    './',
    './index.html',
    './manifest.json',
    './favicon.ico',
    './sites.json',
    './ports.json',
    './data/land_japan_raw.geojson',
    './data/inland_water_japan_w09_05.geojson',
    './data/land-sea-datasets.json',
    ...localPageAssets(html).map(normalizeAsset),
    ...(await directoryAssets('images')).map(normalizeAsset),
    ...(await directoryAssets(path.join('css', 'images'))).map(normalizeAsset)
]);

const appShell = [...assets].sort();
for (const asset of appShell) {
    if (asset === './') continue;
    await fs.access(path.join(projectRoot, asset.slice(2)));
}

const appShellHash = createHash('sha256');
for (const asset of appShell) {
    const relativeFile = asset === './' ? 'index.html' : asset.slice(2);
    appShellHash.update(asset);
    appShellHash.update(await fs.readFile(path.join(projectRoot, relativeFile)));
}
const cacheVersion = appShellHash.digest('hex').slice(0, 12);

const serviceWorker = `/* Generated by scripts/build-service-worker.mjs. */
'use strict';

var CACHE_PREFIX = 'wasa-predictor-';
var CACHE_VERSION = '${cacheVersion}';
var APP_CACHE_NAME = CACHE_PREFIX + 'app-' + CACHE_VERSION;
var TILE_CACHE_NAME = CACHE_PREFIX + 'tiles-v1';
var TILE_CACHE_LIMIT = 500;
var APP_SHELL = ${JSON.stringify(appShell, null, 4)};

function isApiRequest(url) {
    return url.hostname === 'api.v2.sondehub.org' ||
        url.hostname === 'api.open-meteo.com' ||
        url.pathname.startsWith('/api/') ||
        url.pathname === '/__server-info';
}

function isMapTile(url) {
    return url.hostname.endsWith('tile.openstreetmap.org') ||
        url.hostname.endsWith('tile.opentopomap.org') ||
        url.hostname.endsWith('arcgisonline.com') ||
        url.hostname.endsWith('basemaps.cartocdn.com');
}

async function trimCache(cache, maximumEntries) {
    var keys = await cache.keys();
    while (keys.length > maximumEntries) {
        await cache.delete(keys.shift());
    }
}

async function cacheFirstTile(request) {
    var cache = await caches.open(TILE_CACHE_NAME);
    var cached = await cache.match(request);
    if (cached) return cached;
    var response = await fetch(request);
    if (response && (response.ok || response.type === 'opaque')) {
        await cache.put(request, response.clone());
        await trimCache(cache, TILE_CACHE_LIMIT);
    }
    return response;
}

async function networkFirstNavigation(request) {
    var cache = await caches.open(APP_CACHE_NAME);
    try {
        var response = await fetch(request);
        if (response && response.ok) await cache.put('./index.html', response.clone());
        return response;
    } catch (error) {
        return (await cache.match(request)) || (await cache.match('./index.html'));
    }
}

async function staleWhileRevalidate(request) {
    var cache = await caches.open(APP_CACHE_NAME);
    var cached = await cache.match(request);
    var network = fetch(request).then(async function (response) {
        if (response && response.ok && response.type === 'basic') await cache.put(request, response.clone());
        return response;
    }).catch(function () { return null; });
    return cached || (await network) || Response.error();
}

self.addEventListener('install', function (event) {
    event.waitUntil(caches.open(APP_CACHE_NAME).then(function (cache) {
        return cache.addAll(APP_SHELL);
    }));
});

self.addEventListener('activate', function (event) {
    event.waitUntil(caches.keys().then(function (cacheNames) {
        return Promise.all(cacheNames.filter(function (cacheName) {
            return cacheName.startsWith(CACHE_PREFIX) && cacheName !== APP_CACHE_NAME && cacheName !== TILE_CACHE_NAME;
        }).map(function (cacheName) {
            return caches.delete(cacheName);
        }));
    }).then(function () {
        return self.clients.claim();
    }));
});

self.addEventListener('message', function (event) {
    if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', function (event) {
    if (event.request.method !== 'GET') return;
    var requestUrl = new URL(event.request.url);
    if (isApiRequest(requestUrl)) return;
    if (event.request.mode === 'navigate' || requestUrl.pathname.endsWith('.html')) {
        event.respondWith(networkFirstNavigation(event.request));
        return;
    }
    if (isMapTile(requestUrl)) {
        event.respondWith(cacheFirstTile(event.request));
        return;
    }
    if (requestUrl.origin === self.location.origin) {
        event.respondWith(staleWhileRevalidate(event.request));
    }
});
`;

await fs.writeFile(path.join(projectRoot, 'sw.js'), serviceWorker, 'utf8');
console.log(`Generated sw.js with ${appShell.length} app-shell assets (cache ${cacheVersion}).`);
